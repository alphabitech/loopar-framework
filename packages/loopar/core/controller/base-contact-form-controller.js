'use strict'

import BaseController from './base-controller.js';
import { loopar } from '../loopar.js';
import { botContext, verifyCaptcha } from '../document/web-form.js';
import { CONTACT_FORM_ENVELOPE } from '../document/contact-form-base.js';
import { PermissionManager } from '../auth/PermissionManager.js';

const isTrue = v => [1, '1', true, 'true'].includes(v);

/**
 * The public version of a doc structure: drops the fields flagged `internal`
 * (staff-only) and makes the `required_on_website` ones required (a consent
 * the visitor must give, but staff don't when they log a record by hand).
 */
function publicStructure(structure = []) {
  return structure
    .filter(el => !isTrue(el.data?.internal))
    .map(el => {
      const data = isTrue(el.data?.required_on_website) ? { ...el.data, required: 1 } : el.data;
      return { ...el, data, ...(el.elements ? { elements: publicStructure(el.elements) } : {}) };
    });
}

/**
 * Base controller for every entity generated by the Contact Form Builder.
 * Generated controllers extend this and inherit the public submit with the
 * full anti-bot layer; the entity's own metadata drives field validation.
 *
 * Client integration: the page-builder `form` element with
 * document=<Contact Form entity> and action=submit.
 */
export default class BaseContactFormController extends BaseController {
  static publicActions = ['submit'];

  /**
   * Desk staff with edit rights create records like any other entity: every
   * field, no spam pipeline. Everyone else (the website, guests) goes through
   * the public submit. The workspace comes from the signed workspace token.
   */
  #isStaffRequest() {
    if (this.req?.__WORKSPACE_NAME__ !== 'desk') return false;
    const user = loopar.auth.user();
    return !!user && !!PermissionManager.scope(this.document, 'update', user);
  }

  #internalFieldNames(entity) {
    return loopar.utils.fieldList(entity.doc_structure)
      .filter(f => isTrue(f.data?.internal))
      .map(f => f.data.name);
  }

  /** True when the public form shows at least one file/upload field (internal ones don't count). */
  #declaresFileField(entity) {
    const FILE_ELEMENTS = ['file_input', 'image_input', 'file_uploader'];
    return loopar.utils.fieldList(entity.doc_structure)
      .some(f => FILE_ELEMENTS.includes(f.element) && !isTrue(f.data?.internal));
  }

  async publicActionCreate(){
    if (this.#isStaffRequest()) return await super.actionCreate();
    return await this.publicActionSubmit();
  }

  /** Public form render: same as create, without the internal fields. */
  async #renderPublicForm() {
    const document = await loopar.newDocument(this.document);
    if (this.preloaded == true) return await document.values();

    const meta = await document.__meta__();
    meta.Entity.doc_structure = JSON.stringify(
      publicStructure(loopar.utils.JSONparse(meta.Entity.doc_structure, []))
    );
    Object.assign(this.response, meta);
    return await this.render(this.response);
  }

  async publicActionSubmit() {
    if(!this.hasData()) return await this.#renderPublicForm();

    const data = this.data || {};
    const bot = botContext(data);

    // Honeypot: bots that fill everything get a fake success and move on.
    if (bot.honeypot) return this.success('Message sent successfully');

    const ip = this.getClientIP();
    const humanVerified = await verifyCaptcha(loopar, data.captcha_token, ip);

    // Strip envelope + reserved keys: a public sender must never set the
    // workflow columns (status, app, spam_*) nor the primary name.
    const payload = { ...data };
    for (const key of [...CONTACT_FORM_ENVELOPE, 'name', 'captcha_token', '_hp', '_elapsed', 'node', 'form_name']) {
      delete payload[key];
    }

    const entity = (await loopar.newDocument(this.document)).__ENTITY__;
    for (const key of this.#internalFieldNames(entity)) delete payload[key];

    // Public submitters never drive remote-URL imports (SSRF), and may only
    // upload binaries when the form actually declares a file field. Anything
    // that still gets through is validated by the storage upload guard.
    delete payload.__REMOTE_FILES__;
    if (!this.#declaresFileField(entity)) delete payload.__REQ_FILES__;

    const doc = await loopar.newDocument(this.document, payload);

    // A binary is kept only when it belongs to a public file field of the form.
    if (Array.isArray(doc.__DATA__?.__REQ_FILES__)) {
      doc.__DATA__.__REQ_FILES__ = doc.__DATA__.__REQ_FILES__.filter(file => {
        const field = doc.uploadFieldOf(file);
        return field && !isTrue(field.data?.internal);
      });
    }

    await doc.submit({
      fastFill: bot.fastFill,
      humanVerified,
      ip,
      app: loopar.webApp?.name || ''
    });

    // Spam is stored silently — the sender always sees a normal success.
    return this.success('Message sent successfully');
  }

  getClientIP() {
    return this.req?.headers?.['x-forwarded-for']?.split(',')[0]?.trim() ||
           this.req?.headers?.['x-real-ip'] ||
           this.req?.ip ||
           this.req?.socket?.remoteAddress ||
           '';
  }
}
