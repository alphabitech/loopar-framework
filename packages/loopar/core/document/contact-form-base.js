'use strict'

import BaseDocument from './base-document.js';
import { loopar } from '../loopar.js';
import mailchecker from 'mailchecker';

const SPAM_THRESHOLD = 2;
const REJECT_THRESHOLD = 6;


export const CONTACT_FORM_ENVELOPE = [
  'status', 'spam_score', 'spam_reasons', 'normalized_email',
  'ip_address', 'submitted_at', 'app'
];

// Google ignores dots in the local part; "+suffix" is an alias everywhere.
export function normalizeEmail(email) {
  const [rawLocal = '', rawDomain = ''] = String(email || '').trim().toLowerCase().split('@');
  const domain = rawDomain === 'googlemail.com' ? 'gmail.com' : rawDomain;

  let local = rawLocal.split('+')[0];
  if (domain === 'gmail.com') local = local.replace(/\./g, '');

  return domain ? `${local}@${domain}` : '';
}

export function detectSpamHeuristics(text) {
  const hits = [];
  if (!text) return { score: 0, hits };

  let extra = 0;

  const urls = text.match(/https?:\/\/|www\./gi) || [];
  if (urls.length >= 3) hits.push('too-many-urls');

  const textSansUrls = text.replace(/(?:https?:\/\/|www\.)\S+/gi, ' ');
  const letters = textSansUrls.match(/[A-Za-z]/g) || [];
  const upper = textSansUrls.match(/[A-Z]/g) || [];
  if (letters.length >= 50 && upper.length / letters.length > 0.6) hits.push('too-much-caps');

  if (/(.)\1{6,}/.test(text)) hits.push('char-repeat');

  const SPAM_RE = new RegExp(
    String.raw`\b(viagra|cialis|casino|porn|crypto|bitcoin|nft|airdrop|forex|seo backlinks)\b`,
    'gi'
  );

  const uniqueKeywords = new Set(
    (text.match(SPAM_RE) || []).map((m) => m.toLowerCase().replace(/\s+/g, ' '))
  );
  if (uniqueKeywords.size > 0) {
    const points = Math.min(3, uniqueKeywords.size);
    hits.push(points > 1 ? `spam-keywords(+${points})` : 'spam-keyword');
    extra += points - 1;
  }

  const exclamations = (text.match(/!/g) || []).length;
  if (exclamations >= 6) hits.push('too-many-exclamations');

  const hasMoney = /[$€£¥₹]\s?\d{2,}|\b\d{2,}\s?(usd|eur|gbp)\b/i.test(text);
  if (hasMoney && exclamations >= 3) hits.push('money-bait');

  if (/\b(wa\.me|t\.me|telegram\.(me|org)|chat\.whatsapp\.com)\//i.test(text)) hits.push('messenger-link');

  const urlChars = (text.match(/(?:https?:\/\/|www\.)\S+/gi) || []).join('').length;
  if (urlChars > 0 && urlChars / text.length > 0.35) hits.push('mostly-links');

  if (/\[\s*(at|dot)\s*\]/i.test(text)) hits.push('obfuscated-contact');

  return { score: hits.length + extra, hits };
}

/**
 * Base document for every entity generated by the Contact Form Builder.
 *
 * Each generated Contact Form gets its own table (real, typed columns —
 * searchable, listable) and inherits the full public-form security layer
 * from here: metadata validation (via the framework's own field validation
 * on save), content spam scoring with silent-Spam workflow, sender
 * normalization/flagging, rate limiting and admin notification. Subclasses
 * can extend `validateSubmission()` / `beforeSubmit()` for custom logic.
 */
export default class ContactFormBase extends BaseDocument {
  async beforeSave() {
    if (this.__IS_NEW__) {
      // With a naming series the core assigns the name after validation.
      if (!this.__ENTITY__.naming_series) this.name = this.name || this.generateId();
      this.status = this.status || 'New';
      // Set only by submit(): it marks a record that came from the website.
      // Explicit null, otherwise an unset date_time persists as NOW().
      this.submitted_at = this.submitted_at || null;
    } else {
      await this.#keepSubmittedContent();
    }
  }

  /**
   * What a visitor submitted is evidence of what was received: once stored,
   * staff can't change it (corrections go to the documents created from it).
   * Internal fields and the envelope status stay editable. Records created by
   * staff from the desk have no `submitted_at` and stay fully editable.
   */
  lockedFields() {
    return this.contentFields()
      .filter(f => ![1, '1', true, 'true'].includes(f.internal))
      .map(f => f.name);
  }

  async #keepSubmittedContent() {
    const locked = this.lockedFields();
    const stored = await loopar.db.getDoc(this.__ENTITY__.name, this.__DOCUMENT_NAME__, [...locked, 'submitted_at']);
    if (!stored?.submitted_at) return;
    for (const name of locked) this[name] = stored[name];
    this.submitted_at = stored.submitted_at;
  }

  /** Renders the submitted content read-only on website records. */
  async __meta__(...args) {
    const meta = await super.__meta__(...args);
    if (this.__IS_NEW__ || !this.submitted_at) return meta;

    const locked = new Set(this.lockedFields());
    const mark = (nodes = []) => nodes.map(el => ({
      ...el,
      ...(locked.has(el.data?.name) ? { data: { ...el.data, readonly: 1 } } : {}),
      ...(el.elements ? { elements: mark(el.elements) } : {}),
    }));
    meta.Entity.doc_structure = JSON.stringify(mark(loopar.utils.JSONparse(meta.Entity.doc_structure, [])));
    return meta;
  }

  generateId() {
    const timestamp = Date.now().toString(36);
    const random = Math.random().toString(36).substring(2, 6);
    return `CF-${timestamp}-${random}`.toUpperCase();
  }

  /** Writable, non-envelope fields — the actual form content. */
  contentFields() {
    return Object.values(this.fields).filter(f =>
      f.name !== 'name' && !CONTACT_FORM_ENVELOPE.includes(f.name)
    );
  }

  /** First field the entity declares as an email, if any. */
  emailField() {
    return this.contentFields().find(f => f.format === 'email' || f.name === 'email');
  }

  /** Optional hooks for generated subclasses. */
  async validateSubmission() { }
  async beforeSubmit() { }

  /**
   * Public-submission entry point, called by ContactFormController with the
   * anti-bot context. Field validation itself runs inside save() (the same
   * validator every entity uses, from this entity's own metadata).
   */
  async submit(context = {}) {
    this.submitted_at = new Date().toISOString();
    this.ip_address = context.ip || '';
    this.app = context.app || loopar.webApp?.name || '';

    await this.validateSubmission();
    await this.checkRateLimit();

    const { score, hits } = await this.computeSpamScore(context);
    this.spam_score = score;
    this.spam_reasons = hits.join(', ');

    if (score >= REJECT_THRESHOLD) {
      console.warn(`[${this.__ENTITY__.name}] rejected as spam (score=${score}):`, hits);
      loopar.throw('Message rejected');
    }

    const isSpam = score >= SPAM_THRESHOLD;
    if (isSpam) {
      this.status = 'Spam';
      console.warn(`[${this.__ENTITY__.name}] stored as Spam (score=${score}):`, hits);
    }

    await this.beforeSubmit();
    await this.save();

    if (!isSpam) {
      await this.notifyAdmin();
    }

    return isSpam ? 'spam' : 'ok';
  }

  async computeSpamScore(context = {}) {
    const haystack = this.contentFields()
      .map(f => f.value)
      .filter(v => typeof v === 'string')
      .join(' ');

    const { score: heuristicScore, hits } = detectSpamHeuristics(haystack);
    let score = heuristicScore;

    const emailField = this.emailField();
    const email = emailField ? String(emailField.value || '') : '';

    if (email) {
      this.normalized_email = normalizeEmail(email);

      if (!mailchecker.isValid(email)) {
        score += 2;
        hits.push('disposable-email');
      }

      const localPart = email.split('@')[0];
      const domain = (email.toLowerCase().split('@')[1] || '');
      if (['gmail.com', 'googlemail.com'].includes(domain) && (localPart.match(/\./g) || []).length >= 4) {
        score += 2;
        hits.push('dotted-email-alias');
      }

      const previouslyFlagged = await this.countPreviousSpam(this.normalized_email);
      if (previouslyFlagged > 0) {
        score += 1;
        hits.push('previously-flagged-sender');
      }
    }

    // Submitted faster than a human could fill the form. Softer when the
    // captcha positively verified the sender (browser autofill is legit).
    if (context.fastFill) {
      score += context.humanVerified ? 1 : 2;
      hits.push('fast-fill');
    }

    return { score, hits };
  }

  async countPreviousSpam(normalizedEmail) {
    if (!normalizedEmail) return 0;

    try {
      const result = await loopar.db.rawQuery(
        `SELECT COUNT(*) as count FROM ${loopar.db.tableName(this.__ENTITY__.name)}
         WHERE ${loopar.db.escapeId('normalized_email')} = ?
           AND ${loopar.db.escapeId('status')} = ?`,
        [normalizedEmail, 'Spam']
      );
      return result[0]?.count || 0;
    } catch (error) {
      console.warn(`[${this.__ENTITY__.name}] countPreviousSpam failed:`, error.message);
      return 0;
    }
  }

  async checkRateLimit(maxRequests = 5, windowMinutes = 15) {
    if (!this.ip_address) return;

    const windowStart = new Date(Date.now() - windowMinutes * 60 * 1000).toISOString();

    try {
      const result = await loopar.db.rawQuery(
        `SELECT COUNT(*) as count FROM ${loopar.db.tableName(this.__ENTITY__.name)}
         WHERE ${loopar.db.escapeId('ip_address')} = ?
           AND ${loopar.db.escapeId('submitted_at')} >= ?`,
        [this.ip_address, windowStart]
      );

      if ((result[0]?.count || 0) >= maxRequests) {
        loopar.throw('Too many requests. Please try again later.');
      }
    } catch (error) {
      if (error?.message?.includes('Too many requests')) throw error;
      console.warn(`[${this.__ENTITY__.name}] rate limit check failed:`, error.message);
    }
  }

  async notifyAdmin() {
    try {
      const settings = await loopar.getDocument('Email Settings');
      const to = settings.notification_email || settings.from_email;
      if (!to) {
        console.warn('No notification email configured');
        return;
      }

      const escapeHTML = (v) => String(v ?? '')
        .replace(/&/g, '&amp;').replace(/</g, '&lt;')
        .replace(/>/g, '&gt;').replace(/"/g, '&quot;');

      const rows = this.contentFields().map(f =>
        `<tr><td style="padding:4px 8px"><strong>${escapeHTML(f.label || f.name)}</strong></td><td style="padding:4px 8px">${escapeHTML(f.value)}</td></tr>`
      ).join('');

      await loopar.mail.send({
        to,
        replyTo: this.emailField()?.value || undefined,
        subject: `New ${this.__ENTITY__.name}${this.app ? ` (${this.app})` : ''}`,
        html: `
          <h2>${escapeHTML(this.__ENTITY__.name)}</h2>
          ${this.app ? `<p>App: ${escapeHTML(this.app)}</p>` : ''}
          <table border="0" cellspacing="0">${rows}</table>
        `
      });
    } catch (error) {
      console.error(`[${this.__ENTITY__.name}] notify failed:`, error.message);
    }
  }
}
