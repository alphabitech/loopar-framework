import { loopar, CoreInstaller, fileManage, connectionFromInstallData } from "loopar";
import { testServerConnection } from "db-env";
import sha1 from "sha1";
import { ensureCustomerContact, linkPortalUser } from "./modules/crm/portal-access.js";
import { setExternalId } from "./modules/crm/customers.js";
import crypto from "crypto";

/**
 * Generate a random URL-safe password.
 * Used when the tenant is auto-provisioned (no operator typing a password):
 * the customer recovers access via magic-link / password reset.
 */
function generateRandomPassword(length = 20) {
  return crypto.randomBytes(length).toString('base64url').slice(0, length);
}

export default class Installer extends CoreInstaller {
  module = "core";
  // Kept snake_case to match the column name in the App table.
  app_name = "loopar";

  /**
   * System roles (seeded by CoreInstaller.seedRoles after every install/update).
   *
   * Base roles grant ENTRY, not data: a user with only `Desk User` sees an
   * empty desk until an application role (declared by each app in its own
   * installer, e.g. "<AppName> Manager" → App:<AppName>:*) gives it data. Safe by
   * default — `*:list` for every desk user would turn "can log in" into "can
   * read the whole database", and `*:list own` breaks selects (a user couldn't
   * pick a category created by someone else).
   */
  static defaultRoles = false;   // System Manager already is "Loopar Manager"

  static roles = [
    {
      name: "System Manager",
      description: "Full access to every document and action (like Administrator, but a regular user).",
      grants: [{ document: "*", action: "*" }],
    },
    {
      name: "Desk User",
      description: "Can enter the desk and manage their own profile. Data access comes from application roles.",
      grants: [{ document: "Profile", action: "*" }],
    },
    {
      name: "Web User",
      description: "Portal / website account. Apps grant their own documents here, usually with scope 'own'.",
      grants: [],
    },
  ];

  /**
   * Auto-seed credentials from the tenant env when missing.
   * `CUSTOMER_EMAIL` is set by the control-plane provisioner so the first
   * Administrator is the paying customer, not a generic `admin`. Password is
   * random; customer recovers via email reset.
   */
  #seedFromEnv() {
    if (!this.email && process.env.CUSTOMER_EMAIL) {
      this.email = process.env.CUSTOMER_EMAIL;
    }
    if (!this.admin_password) {
      this.admin_password = generateRandomPassword();
      this.confirm_password = this.admin_password;
      this._autoGeneratedPassword = true;
    }
    if (!this.company && process.env.TENANT_ID) {
      this.company = process.env.TENANT_ID;
    }
  }

  async validate() {
    this.#seedFromEnv();

    if(this.admin_password !== this.confirm_password){
      loopar.throw("Passwords do not match");
    }

    // Enforce a strong password ONLY when a human typed it. Auto-generated
    // (cloud-provisioned) passwords are random 20-char base64url and the user
    // resets them via magic-link, so they are exempt.
    if (!this._autoGeneratedPassword) {
      const strong = /^(?=.*[a-z])(?=.*[A-Z])(?=.*[0-9])(?=.*[^A-Za-z0-9]).{8,}$/;
      if (!strong.test(this.admin_password || "")) {
        loopar.throw("Password must be at least 8 characters and include uppercase, lowercase, number and special character.");
      }
    }

    if(this.company.length < 3){
      loopar.throw("Company name must be at least 3 characters long");
    }

    if(this.email.length < 3){
      loopar.throw("Email must be at least 3 characters long");
    }

   /* if(this.admin_password === "admin"){
      loopar.throw("Password cannot be 'admin'");
    }

    if(this.email === "admin"){
      loopar.throw("Email cannot be 'admin'");
    }*/

    if(this.company === "admin"){
      loopar.throw("Company name cannot be 'admin'");
    }

    return await super.validate();
  }

  async install(reinstall = false) {
    if(reinstall) {
      const result = await super.install(true);
      await this.#migrateAppTypeToHasWebsite();
      await this.#restoreNameIdentity();
      await this.#dropModuleGroup();
      await this.#migrateCustomers();
      await this.#migrateCompany();
      return result;
    }
    await this.validate(reinstall);

    console.log("Installing Loopar");
    // What is on disk before the install: what the tenant goes back to if the
    // install breaks half-way.
    const previousConfig = structuredClone(fileManage.getConfigFile('db.config') || {});
    // The wizard's "Database" step. Without it (cloud provisioning, tests,
    // pre-seeded tenants) the db.config already on disk is used.
    const connection = connectionFromInstallData(this);
    await this.#assertServerReachable(connection);

    try {
      loopar.installingApp = "loopar";
      if (connection) {
        await loopar.setDbConfig(connection);
        // Pools of the previous connection (maybe another engine) must not
        // be reused by the DDL below.
        await loopar.db.close();
      }
      await this.setDbConfig();
      console.log("DB Config set");
      // alterSchema BEFORE initialize: when the autogenerated DB name doesn't
      // exist yet, the connector's MySQL retry path falls back to
      // information_schema and leaves `this.knex` pointing there. Subsequent
      // ALTER TABLE statements would then run against information_schema (no
      // permission). Creating the DB first via `coreConnection` (a separate
      // server-level handle that doesn't need a target DB) lets initialize(true)
      // connect straight to the new schema.
      await loopar.db.alterSchema();
      console.log("Schema Altered");
      await loopar.db.initialize(true);
      console.log("DB Initialized");
      await this.#makeCoreTable();
      console.log("Core Table Created");
      await super.install();
      await this.insertAdministratorUser();
      // The install is complete only with its Administrator: without it the
      // tenant could never be signed into, so it is rolled back like any failure.
      if (!(await loopar.db.count("User", "Administrator"))) {
        throw new Error("The Administrator user was not created.");
      }
    } catch (e) {
      await this.#rollbackFreshInstall(previousConfig);
      throw e;
    }

    await this.#seedOrganization();

    // super.install() built while the Administrator didn't exist yet, so that
    // build saw a not-installed tenant (and dropped loopar from installed-apps).
    // Now the install is complete: register the app and build for real.
    await loopar.setApp({ loopar: true });
    await loopar.build();
    return true;
  }

  /** Nothing is written when the database server can't be reached. */
  async #assertServerReachable(connection) {
    const result = connection
      ? await testServerConnection(connection)
      : { ok: await loopar.db.testServer(), error: "the saved connection does not reach its server" };
    if (result.ok) return;
    loopar.throw({
      status: 503,
      code: 'DB_UNREACHABLE',
      title: 'Database connection',
      message: `Could not connect to the database server: ${result.error}`,
    });
  }

  /**
   * A first install that failed half-way is undone completely: the database
   * it created is dropped and db.config goes back to what was on disk before,
   * so the tenant lands on the install wizard again instead of booting as
   * installed with no Administrator. Each install creates a brand-new
   * database (setDbConfig), so nothing else lives in the one being dropped.
   * Rollback errors are logged, never thrown: the install error is the one
   * the wizard must show.
   */
  async #rollbackFreshInstall(connectConfig) {
    const db = loopar.db;
    const database = db.database;
    console.error(`[Installer] Install failed, rolling back${database ? ` database "${database}"` : ""}`);

    try {
      if (db.isSQLiteLike) {
        // The file IS the database: empty it instead of deleting it (a locked
        // file can't be removed on every platform).
        await this.#dropSqliteTables();
        await db.close();
      } else if (database && database !== connectConfig.database) {
        // Release the tenant pool first: Postgres/MSSQL refuse to drop a
        // database with open connections.
        await db.close();
        await db.dropSchema(database);
        await db.close();
      }
    } catch (e) {
      console.error(`[Installer] Rollback could not remove the database: ${e.message}`);
    }

    try {
      await loopar.setDbConfig(connectConfig);
      if (loopar.installedApps?.loopar) await loopar.unsetApp("loopar");
      loopar.installingApp = null;
      await loopar.db.initialize();
      await loopar.build();
    } catch (e) {
      console.error(`[Installer] Rollback could not restore the previous db.config: ${e.message}`);
    }
  }

  /**
   * The installer's "Organization" block: the Company single (identity and
   * regional defaults) and the interface language of System Settings.
   */
  async #dropSqliteTables() {
    const knex = loopar.db.knex;
    if (!knex) return;
    const tables = await knex("sqlite_master")
      .where({ type: "table" })
      .andWhereNot("name", "like", "sqlite_%")
      .pluck("name");
    await knex.raw("PRAGMA foreign_keys = OFF");
    for (const table of tables) await knex.schema.dropTableIfExists(table);
  }

  async #seedOrganization() {
    try {
      const company = await loopar.getDocument("Company");
      company.company_name ||= this.company;
      for (const field of ["country", "time_zone", "currency"]) {
        if (this[field] && !company[field]) company[field] = this[field];
      }
      await company.save();

      const settings = await loopar.getDocument("System Settings");
      settings.languaje = ["En", "Es"].includes(this.language) ? this.language : (settings.languaje || "En");
      await settings.save();
    } catch (e) {
      // The tenant is installed; Company can be completed from the desk.
      console.error("[Installer] Organization not seeded:", e.message);
    }
  }

  /**
   * One-time migration (7.4.3): the company identity moved to the Company
   * single. Fills its empty fields from the default (else first) Letterhead
   * and from System Settings (logo, time zone, country), then drops the old
   * Letterhead columns and System Settings values. Idempotent; delete once
   * every tenant is past 7.4.3.
   */
  async #migrateCompany() {
    const q = () => loopar.db.qx();
    const schema = () => q().schema;
    const LETTERHEAD_COLUMNS = ["company_name", "logo", "address", "phone", "email", "website"];
    const SETTINGS_FIELDS = ["logo", "time_zone", "country"];
    try {
      if (!loopar.getRef("Company", false)) return;

      const old = Object.fromEntries(
        (await q()("Document Single Values").select("field", "value").where({ document: "System Settings" }).whereIn("field", SETTINGS_FIELDS))
          .map((r) => [r.field, r.value])
      );

      let letterhead = null;
      const letterheadColumns = [];
      if (await schema().hasTable("Letterhead")) {
        for (const c of LETTERHEAD_COLUMNS) if (await schema().hasColumn("Letterhead", c)) letterheadColumns.push(c);
        if (letterheadColumns.length) {
          const rows = await q()("Letterhead").select([...letterheadColumns, "is_default"]);
          letterhead = rows.find((r) => loopar.utils.trueValue(r.is_default)) || rows[0] || null;
        }
      }

      const countries = { USA: "US", Honduras: "HN" };
      const country = countries[old.country] || (/^[A-Z]{2}$/.test(old.country || "") ? old.country : null);
      const values = {
        company_name: letterhead?.company_name,
        logo: letterhead?.logo || old.logo,
        address: letterhead?.address,
        phone: letterhead?.phone,
        email: letterhead?.email,
        website: letterhead?.website,
        country,
        time_zone: old.time_zone && old.time_zone !== "GMT" ? old.time_zone : null,
      };

      const company = await loopar.getDocument("Company");
      let changed = false;
      for (const [field, value] of Object.entries(values)) {
        if (value && !company[field]) { company[field] = value; changed = true; }
      }
      if (changed) {
        if (!company.company_name) company.company_name = loopar.tenantId || "Company";
        await company.save();
        console.log("[Installer] Company filled from Letterhead / System Settings");
      }

      if (letterheadColumns.length) {
        await schema().alterTable("Letterhead", (t) => { for (const c of letterheadColumns) t.dropColumn(c); });
      }
      await q()("Document Single Values").where({ document: "System Settings" }).whereIn("field", SETTINGS_FIELDS).delete();
    } catch (e) {
      console.error("[Installer] Company migration failed:", e.message);
    }
  }

  /**
   * One-time data migration (7.1.6): App.type ("Desk App" | "Web App") was
   * replaced by the App.has_website switch. The old `type` column survives as
   * an orphan after alterSchema, so it can still be read here. Idempotent;
   * delete this method once every tenant has been updated past 7.1.6.
   */
  /**
   * One-time migration (7.2.1): an experimental build made meta rows unique by
   * (module, name). Entity names are unique per tenant again: restore
   * UNIQUE(name) on Entity and every builder table. Idempotent (no-op where
   * UNIQUE(name) never left); delete once dev tenants are past 7.2.1.
   */
  async #restoreNameIdentity() {
    const tables = new Set(["Entity", ...Object.keys(loopar.getTypes() || {})]);
    for (const table of tables) {
      try {
        await loopar.db.ensureNameUniqueKey(table);
      } catch (e) {
        console.error(`[Installer] UNIQUE(name) for "${table}" failed:`, e.message);
      }
    }
  }

  /**
   * One-time migration (7.3.0): Module Group was removed — the desk menu is
   * grouped by App now. Drops the entity (meta row, permissions, table), the
   * Module.module_group column, and the duplicated "web"/"integrations"
   * modules an old installer snapshot created from folder names (the real
   * modules are "Web"/"Integrations"). Names are matched exactly in JS:
   * MySQL compares case-insensitively and would hit the real modules.
   * Idempotent; delete once every tenant is past 7.3.0.
   */
  async #dropModuleGroup() {
    const q = () => loopar.db.qx();
    // A knex SchemaBuilder accumulates statements: take a fresh one per call.
    const schema = () => q().schema;

    try {
      const entityModules = new Set((await q()("Entity").select("module")).map(r => r.module));
      const orphans = (await q()("Module").select("id", "name", "app_name"))
        .filter(m => ["web", "integrations"].includes(m.name) && m.app_name === "loopar" && !entityModules.has(m.name));
      if (orphans.length) {
        await q()("Module").whereIn("id", orphans.map(m => m.id)).delete();
        console.log(`[Installer] Removed duplicated modules: ${orphans.map(m => m.name).join(", ")}`);
      }

      const meta = (await q()("Entity").select("id", "name")).filter(e => e.name === "Module Group");
      if (meta.length) await q()("Entity").whereIn("id", meta.map(e => e.id)).delete();

      if (await schema().hasTable("Permission")) {
        const perms = (await q()("Permission").select("id", "document")).filter(p => p.document === "Module Group");
        if (perms.length) await q()("Permission").whereIn("id", perms.map(p => p.id)).delete();
      }

      if (await schema().hasTable("Module Group")) await schema().dropTable("Module Group");
      if (await schema().hasColumn("Module", "module_group")) {
        await schema().alterTable("Module", t => t.dropColumn("module_group"));
      }

      if (meta.length) console.log("[Installer] Module Group removed");
    } catch (e) {
      console.error("[Installer] Module Group removal failed:", e.message);
    }
  }

  /**
   * One-time migration (7.4.x): Customer moved from the control app to the
   * core crm module. Existing rows get a customer_name and a capitalized
   * status, the old `portal_user` link becomes a Customer Contact whose
   * `user` is that portal user, and `stripe_customer_id` becomes an external
   * id (source "stripe"); then the orphan columns are dropped.
   * Idempotent; delete once every tenant is past 7.4.1.
   */
  async #migrateCustomers() {
    const q = () => loopar.db.qx();
    const schema = () => q().schema;
    try {
      if (!(await schema().hasTable("Customer"))) return;
      const has = async (column) => await schema().hasColumn("Customer", column);

      await q()("Customer").where(b => b.whereNull("customer_name").orWhere("customer_name", "")).update({ customer_name: q().raw("??", ["name"]) });
      await q()("Customer").where({ status: "active" }).update({ status: "Active" });
      await q()("Customer").where({ status: "inactive" }).update({ status: "Inactive" });

      let failed = 0;
      if (await has("portal_user")) {
        let query = q()("Customer").select("name", "email", "customer_name", "portal_user").whereNotNull("portal_user");
        if (await has("__deleted_at__")) query = query.whereNull("__deleted_at__");
        const rows = await query;
        for (const row of rows) {
          if (!row.portal_user) continue;
          try {
            const user = await loopar.db.getRow("User", row.portal_user, ["name", "email"]);
            if (!user) continue;
            const contact = await ensureCustomerContact(row.name, { email: row.email || user.email, full_name: row.customer_name });
            await linkPortalUser(contact, user.name);
          } catch (e) {
            failed++;
            console.error(`[Installer] Customer ${row.name}: portal user not migrated:`, e.message);
          }
        }
      }

      if (await has("stripe_customer_id")) {
        const rows = await q()("Customer").select("name", "stripe_customer_id").whereNotNull("stripe_customer_id").whereNot("stripe_customer_id", "");
        for (const row of rows) {
          try {
            await setExternalId(row.name, "stripe", row.stripe_customer_id);
          } catch (e) {
            failed++;
            console.error(`[Installer] Customer ${row.name}: Stripe id not migrated:`, e.message);
          }
        }
      }

      // Keep the old columns while anything is still to migrate (the next update retries).
      if (failed) return;
      for (const column of ["portal_user", "portal_invited_at", "stripe_customer_id", "tax_id"]) {
        if (await has(column)) await schema().alterTable("Customer", t => t.dropColumn(column));
      }
    } catch (e) {
      console.error("[Installer] Customer migration failed:", e.message);
    }
  }

  async #migrateAppTypeToHasWebsite() {
    const columns = await loopar.db.getTableDescription("App");
    if (!columns.some(c => c.name.toLowerCase() === "type")) return;

    const table = loopar.db.tableName("App");
    await loopar.db.raw(
      `UPDATE ${table} SET ${loopar.db.escapeId("has_website")} = 1 WHERE ${loopar.db.escapeId("type")} = ?`,
      ["Web App"]
    );
    console.log("[Installer] App.type migrated to App.has_website");
  }

  async insertAdministratorUser() {
    let user = null
    if (await loopar.db.getValue("User", 'name', "Administrator", { ifNotFound: false })){
      user = await loopar.getDocument("User", "Administrator");
    }else{
      user = await loopar.newDocument("User");
    }

    user.name = "Administrator";
    user.email = this.email;
    user.password = this.admin_password;
    user.confirm_password = this.confirm_password;
    user.__document_status__ = "Active";

    // When the password is auto-generated (cloud-provisioned tenant) we mark
    // the user so the desk can show a "set your password" banner and the
    // Profile can offer the email-reset shortcut. Recovery flow clears it.
    if (this._autoGeneratedPassword) {
      user.must_change_password = 1;
    }

    console.log(`Creating Administrator user for ${this.email}`);
    await user.save({ validate: false });
    console.log("Administrator user created");

    if (this._autoGeneratedPassword) {
      console.log(
        `[Installer] Password was auto-generated for ${this.email}. ` +
        `Customer should set their own via the magic-link or password-reset flow.`
      );
    }

    return true;
  }

  async setDbConfig() {
    const db_config = fileManage.getConfigFile('db.config');
    db_config.database = 'db_' + sha1(this.company + new Date().toISOString()).substring(0, 16);
    return await loopar.setDbConfig(db_config);
  }

  async #makeCoreTable() {
    const ref = loopar.getRef("Entity");
    const coreData = await this.getDocumentData("Entity", ref.__ROOT__);

    const Entity = await loopar.newDocument("Entity", coreData);
    await Entity.initialize({ validate: false });
  }
}