/**
 * A first install that breaks half-way must not leave a tenant that boots as
 * installed with nobody able to sign in.
 *
 *   - install fails after the tables → rolled back to the Connect state
 *   - schema present but no Administrator → not installed, routed to install
 *   - creating the Administrator afterwards completes the tenant
 */
import { test, after } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {
  loopar,
  tenant,
  getOrCreateTenantInstance,
  evictTenantInstance,
  requestContext,
} from "loopar";
import { bootTestTenant, ADMIN } from "../support/tenant.js";

const root = process.cwd();
const { default: Installer } = await import(path.join(root, "apps", "loopar", "installer.js"));
const { SystemValidation } = await import(
  path.join(root, "packages", "loopar", "core", "server", "router", "router-utils.js")
);

const name = `__loopar_rollback_${process.pid}__`;
const site = path.join(root, "sites", name);
const sqliteFile = path.join(site, "database", `${name}.sqlite`);
const connectConfig = { dialect: "sqlite", connection: {} };
const run = (fn) => requestContext.run({ tenant: { name } }, fn);

let installed = null;

after(async () => {
  try { await run(async () => loopar.db?.knex?.destroy?.()); } catch { /* not loaded */ }
  evictTenantInstance(name);
  fs.rmSync(site, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  await installed?.teardown();
});

class BrokenInstaller extends Installer {
  async insertAdministratorUser() {
    throw new Error("simulated failure creating the Administrator");
  }
}

test("an install that fails after creating the tables is rolled back", async () => {
  fs.rmSync(site, { recursive: true, force: true });
  await tenant.saveTenant({ NAME: name, status: "active" });
  fs.mkdirSync(path.join(site, "config"), { recursive: true });
  fs.writeFileSync(path.join(site, "config", "db.config.json"), JSON.stringify(connectConfig));

  await getOrCreateTenantInstance(name);
  await run(async () => {
    await assert.rejects(
      new BrokenInstaller({
        app_name: "loopar",
        company: ADMIN.company,
        email: ADMIN.email,
        admin_password: ADMIN.password,
        confirm_password: ADMIN.password,
      }).install(),
      /simulated failure/,
    );

    assert.equal(loopar.__installed__, false, "not installed after the failure");
    assert.equal(loopar.installingApp ?? null, null);
    assert.equal(loopar.installedApps?.loopar, undefined, "loopar not registered as installed");
    assert.deepEqual(
      JSON.parse(fs.readFileSync(path.join(site, "config", "db.config.json"), "utf8")),
      connectConfig,
      "db.config is back to what Connect saved",
    );
    assert.equal(await loopar.db.hasTable("User"), false, "the half-built schema is gone");
    assert.equal(SystemValidation.getRedirectPath(loopar), SystemValidation.getStatus(loopar).installPath);
  });
});

test("the same tenant installs cleanly on the next attempt", async () => {
  await run(async () => {
    await new Installer({
      app_name: "loopar",
      company: ADMIN.company,
      email: ADMIN.email,
      admin_password: ADMIN.password,
      confirm_password: ADMIN.password,
    }).install();

    assert.equal(loopar.__installed__, true);
    assert.equal(loopar.installedApps?.loopar, true);
    assert.equal(await loopar.db.count("User", "Administrator"), 1);
    assert.ok(fs.existsSync(sqliteFile));
  });
});

test("a schema without the Administrator is not installed and routes to install", async () => {
  installed = await bootTestTenant();
  await installed.run(async () => {
    assert.equal(loopar.__installed__, true);

    await loopar.db.knex("User").where({ name: "Administrator" }).del();
    await loopar.build();

    assert.equal(loopar.__installed__, false);
    assert.equal(loopar.__wasInstalled__, false, "install wizard, not /system/update");
    const status = SystemValidation.getStatus(loopar);
    assert.equal(SystemValidation.getRedirectPath(loopar), status.installPath);
  });
});

test("creating the Administrator (admin-reset) completes the tenant", async () => {
  await installed.run(async () => {
    const installer = new Installer({
      email: ADMIN.email,
      admin_password: ADMIN.password,
      confirm_password: ADMIN.password,
    });
    installer._autoGeneratedPassword = true;
    await installer.insertAdministratorUser();
    await loopar.build();

    assert.equal(loopar.__installed__, true);
    const admin = await loopar.db.getDoc("User", "Administrator", ["email", "must_change_password"]);
    assert.equal(admin?.email, ADMIN.email);
    assert.equal(Number(admin?.must_change_password), 1);
  });
});
